// Generates the library declarations shipped for "Add Widget Types" (src/widget-types/, docs/WIDGETS-PLAN.md §2, §9):
// - libraries.d.ts: recharts, motion/react, d3 and lodash with their real export names and loose types
//   (components take any props, everything else is `any`), plus the aliases the compiler accepts
//   (motion, framer-motion, d3-scale, …). Names are what the compiler checks; the types stay small.
// - lucide-react.d.ts: one LucideIcon per icon name the compiler accepts (lucide's own list, aliases included).
// React, the SDK and the UI shims are written by hand (react.d.ts, explainer.d.ts, ui.d.ts).
// Usage: node scripts/widget-types.ts [--check]   (--check exits 1 when the committed files are out of date)
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { D3_MODULES, WIDGET_ALIASES } from '../src/shared/widget-imports.ts';
import { generateWidgetData, type LucideData } from './widget-data.ts';

const OUT = 'src/widget-types';
const HEADER = '// Generated by scripts/widget-types.ts from the installed libraries; do not edit.\n';

const isComponent = (name: string) => /^[A-Z][a-z0-9]/.test(name) || /^[A-Z]$/.test(name);
const isHook = (name: string) => /^use[A-Z]/.test(name);
const isIdentifier = (name: string) => /^[A-Za-z_$][\w$]*$/.test(name) && !RESERVED.has(name);
const RESERVED = new Set(['default', 'delete', 'new', 'in', 'function', 'class', 'var', 'const', 'let', 'export', 'import', 'return', 'typeof', 'void', 'this', 'null', 'true', 'false', 'switch', 'case', 'do', 'if', 'else', 'for', 'while', 'with', 'try', 'catch', 'finally', 'throw', 'break', 'continue', 'debugger', 'enum', 'extends', 'super', 'yield', 'await', 'instanceof']);

/** Wraps a long `export const a: T, b: T;` list at about 120 columns. */
function constList(names: string[], type: string): string {
  if (!names.length) return '';
  const lines: string[] = [];
  let line = '  export const';
  names.forEach((n, i) => {
    const item = ` ${n}: ${type}${i === names.length - 1 ? ';' : ','}`;
    if (line.length + item.length > 120) {
      lines.push(line);
      line = '   ';
    }
    line += item;
  });
  lines.push(line);
  return `${lines.join('\n')}\n`;
}

function moduleDecl(spec: string, names: string[]): string {
  const ok = names.filter((n) => n !== 'default' && isIdentifier(n) && !n.startsWith('__'));
  let body = '';
  body += constList(ok.filter(isComponent), '__CxAnyComponent');
  body += constList(ok.filter(isHook), '(...args: any[]) => any');
  body += constList(ok.filter((n) => !isComponent(n) && !isHook(n)), 'any');
  if (names.includes('default')) body += '  const _default: any;\n  export default _default;\n';
  return `declare module '${spec}' {\n${body}}\n`;
}

export function librariesDts(exports: Record<string, string[]>): string {
  let out = HEADER;
  out += '// Loose types: real export names (a misspelled import is an error, as in the compiler), `any` values.\n';
  out += 'type __CxAnyComponent = __CxReact.ComponentType<any>;\n\n';
  for (const spec of ['recharts', 'motion/react', 'd3', 'lodash']) out += `${moduleDecl(spec, exports[spec] ?? [])}\n`;
  const aliases = Object.entries(WIDGET_ALIASES).sort(([a], [b]) => a.localeCompare(b));
  for (const [alias, target] of aliases) {
    if (!(D3_MODULES as readonly string[]).includes(alias) && target !== 'motion/react') continue;
    out += `declare module '${alias}' { export * from '${target}'; }\n`;
  }
  return out;
}

export function lucideDts(data: LucideData): string {
  const all = new Set([...Object.keys(data.icons), ...Object.keys(data.aliases)].filter(isIdentifier));
  // Every name comes as Name, NameIcon and LucideName: declare the bases and let a mapped type add the rest.
  const bases = [...all].filter((n) => all.has(`${n}Icon`) && all.has(`Lucide${n}`)).sort();
  const covered = new Set(bases.flatMap((n) => [n, `${n}Icon`, `Lucide${n}`]));
  const extra = [...all].filter((n) => !covered.has(n)).sort();
  const union = (names: string[]) => {
    const lines: string[] = [];
    let line = '   ';
    for (const n of names) {
      const item = ` | '${n}'`;
      if (line.length + item.length > 120) {
        lines.push(line);
        line = '   ';
      }
      line += item;
    }
    lines.push(line);
    return lines.join('\n');
  };
  let out = HEADER;
  out += '// Every icon name widgets can import, as lucide-react exports them: Name, NameIcon and LucideName (renamed icons\n';
  out += '// included). Only the icons a widget imports are sent to it.\n';
  out += "declare module 'lucide-react' {\n";
  out += `  type Name =\n${union(bases)};\n`;
  out += `  type Extra = ${extra.length ? `\n${union(extra)}` : 'never'};\n`;
  out += '  interface Props { size?: number | string; color?: string; strokeWidth?: number | string; absoluteStrokeWidth?: boolean; className?: string; [attribute: string]: any }\n';
  out += '  type Icon = __CxReact.FC<Props>;\n';
  out += '  const icons: { readonly [K in Name as K | `${K}Icon` | `Lucide${K}`]: Icon } & { readonly [K in Extra]: Icon };\n';
  out += '  namespace icons {\n    type LucideIcon = Icon;\n    type LucideProps = Props;\n  }\n';
  out += '  export = icons;\n}\n';
  return out;
}

export async function generateWidgetTypes(root = process.cwd()): Promise<Record<string, string>> {
  const tmp = mkdtempSync(join(tmpdir(), 'cx-widget-types-'));
  try {
    await generateWidgetData(tmp, root);
    const exports = JSON.parse(readFileSync(join(tmp, 'exports.json'), 'utf8')) as Record<string, string[]>;
    const lucide = JSON.parse(readFileSync(join(tmp, 'lucide.json'), 'utf8')) as LucideData;
    return { 'libraries.d.ts': librariesDts(exports), 'lucide-react.d.ts': lucideDts(lucide) };
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const check = process.argv.includes('--check');
  const files = await generateWidgetTypes();
  let stale = false;
  for (const [name, text] of Object.entries(files)) {
    const path = join(OUT, name);
    if (check) {
      let current = '';
      try {
        current = readFileSync(path, 'utf8');
      } catch { /* missing */ }
      // A Windows checkout may have converted the committed files to CRLF.
      if (current.replace(/\r\n/g, '\n') !== text) {
        console.error(`${path} is out of date: run node scripts/widget-types.ts`);
        stale = true;
      }
    } else {
      writeFileSync(path, text);
      console.log(`${path}: ${(text.length / 1024).toFixed(1)} KB`);
    }
  }
  if (stale) process.exit(1);
}
